const PanelBlocks: React.FC<PanelComponentProps> = ({ label, value }) => {
  const [showListView] = useAtom(showListViewAtom);

  const formatValue = (value: string, label: string) => {
    const lowerCaseLabel = label.toLocaleLowerCase();
    if (lowerCaseLabel === 'tps') {
      return Number(value).toFixed(2);
    }
    if (lowerCaseLabel === 'blocks' || lowerCaseLabel === 'transactions') {
      return Number(value).toLocaleString();
    }
    return value;
  };

  return (
    <div className={showListView ? 'panel-blocks-listview' : 'panel-blocks'}>
      <div className="header">
        <div className="label-container">
          <div className="label">{label}</div>
        </div>
        <div className="icon-container">{getIcon(label)}</div>
      </div>
      <div className="value-container">
        <div className="value-background">
          <div className="value">{value == '' || value == null ? '--' : formatValue(value, label)}</div>
        </div>
      </div>
    </div>
  );
};

